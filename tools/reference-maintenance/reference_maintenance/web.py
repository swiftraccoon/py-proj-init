TRANSFORMATIONS = (
    "timeless-documentation.md is a Markdown rendering generated from source.html",
    "ATTRIBUTION.md is generated by the maintenance tool",
)
ATTRIBUTION = """# Attribution

Timeless documentation, by Google.

Source: https://developers.google.com/style/timeless-documentation

Text is licensed under [Creative Commons Attribution 4.0 International](https://creativecommons.org/licenses/by/4.0/).
Code samples are licensed under [Apache License 2.0](https://www.apache.org/licenses/LICENSE-2.0).

`source.html` preserves the downloaded page and its original license notice.
`timeless-documentation.md` is a mechanically extracted Markdown version of the
article; site navigation and the generated page summary are omitted.
Retrieval time and file hashes are recorded in `../manifest.json`.
"""
VOID_TAGS = frozenset(
    {
        "area",
        "base",
        "br",
        "col",
        "embed",
        "hr",
        "img",
        "input",
        "link",
        "meta",
        "param",
        "source",
        "track",
        "wbr",
    }
)


def _empty_children() -> list[Node | str]:
    return []


@dataclass
class Node:
    """A small HTML tree sufficient for article extraction and inline markup."""

    tag: str
    attrs: dict[str, str | None] = field(default_factory=dict[str, str | None])
    children: list[Node | str] = field(default_factory=_empty_children)

    def descendants(self) -> list[Node]:
        """Collect this node and its descendants in document order."""
        result: list[Node] = [self]
        for child in self.children:
            if isinstance(child, Node):
                result.extend(child.descendants())
        return result


class ArticleParser(HTMLParser):
    """Parse HTML without fetching resources or executing scripts."""

    def __init__(self) -> None:
        """Create the document root and open-element stack."""
        super().__init__(convert_charrefs=True)
        self.root = Node("document")
        self.stack = [self.root]

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        """Append a node and track non-void elements."""
        node = Node(tag, dict(attrs))
        self.stack[-1].children.append(node)
        if tag not in VOID_TAGS:
            self.stack.append(node)

    def handle_endtag(self, tag: str) -> None:
        """Close the matching element while tolerating optional end tags."""
        for index in range(len(self.stack) - 1, 0, -1):
            if self.stack[index].tag == tag:
                del self.stack[index:]
                break

    def handle_startendtag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        """Handle self-closing syntax without leaving an open element."""
        self.handle_starttag(tag, attrs)
        if tag not in VOID_TAGS:
            self.handle_endtag(tag)

    def handle_data(self, data: str) -> None:
        """Preserve text within the active element."""
        self.stack[-1].children.append(data)


def _collapse(text: str) -> str:
    return re.sub(r"\s+", " ", text)


def _table(node: Node, base: str) -> str:
    rows: list[str] = []
    for row in node.descendants():
        if row.tag != "tr":
            continue
        cells = [
            _collapse(_render(cell, base)).strip().replace("|", "\\|")
            for cell in row.children
            if isinstance(cell, Node) and cell.tag in {"td", "th"}
        ]
        rows.append("| " + " | ".join(cells) + " |")
        if len(rows) == 1:
            rows.append("| " + " | ".join("---" for _ in cells) + " |")
    return "\n\n" + "\n".join(rows) + "\n\n"


def _format(node: Node, content: str, base: str) -> str:
    stripped = content.strip()
    wrappers = {
        "em": "*{}*",
        "i": "*{}*",
        "strong": "**{}**",
        "b": "**{}**",
        "code": "`{}`",
        "br": "\n",
    }
    if node.tag in wrappers:
        return wrappers[node.tag].format(stripped)
    if node.tag == "a":
        return f"[{stripped}]({urljoin(base, node.attrs.get('href') or '')})"
    if re.fullmatch(r"h[1-6]", node.tag):
        return f"\n\n{'#' * int(node.tag[1])} {stripped}\n\n"
    if node.tag == "li":
        return f"\n- {_collapse(stripped)}\n"
    if node.tag in {"p", "ul", "ol", "div", "section", "blockquote"}:
        return f"\n\n{stripped}\n\n"
    return content


def _render(node: Node | str, base: str) -> str:
    if isinstance(node, str):
        return _collapse(node)
    if node.tag in {"script", "style", "devsite-key-takeaways-panel"}:
        return ""
    if node.tag == "table":
        return _table(node, base)
    content = "".join(_render(child, base) for child in node.children)
    return _format(node, content, base)


def timeless_markdown(raw: bytes, url: str) -> bytes:
    """Extract the article; fail if its license, body, or expected structure changed."""
    html = raw.decode("utf-8")
    require(
        "creativecommons.org/licenses/by/4.0/" in html,
        "Expected page license notice missing",
    )
    parser = ArticleParser()
    parser.feed(html)
    parser.close()
    articles = [
        node
        for node in parser.root.descendants()
        if "devsite-article-body" in (node.attrs.get("class") or "").split()
    ]
    require(
        len(articles) == 1,
        "Expected one timeless documentation article; review site markup",
    )
    text = re.sub(r"\n[ \t]+", "\n", _render(articles[0], url).strip())
    text = re.sub(r"\n{3,}", "\n\n", text)
    require(
        "Timeless documentation is documentation" in text
        and "## Words and phrases to avoid" in text,
        "Timeless documentation content changed; review extraction",
    )
    return f"# Timeless documentation\n\n{text}\n".encode()


def download(url: str) -> bytes:
    """Download one HTML page with an explicit timeout and bounded response."""
    require(url.startswith("https://"), "Web snapshots require HTTPS")
    # Source definitions supply the URL; require HTTPS before constructing a
    # request and check the redirect target before reading downloaded content.
    request = Request(  # noqa: S310 -- HTTPS validated above
        url, headers={"User-Agent": "py-proj-init reference-sync/1.0"}
    )
    with urlopen(request, timeout=60) as response:  # noqa: S310 -- validated URL
        require(
            response.geturl().startswith("https://"),
            "Web snapshot redirected away from HTTPS",
        )
        raw: bytes = response.read(10 * 1024 * 1024 + 1)
    require(0 < len(raw) <= 10 * 1024 * 1024, "Web response is empty or exceeds 10 MiB")
    return raw


def _preserve_outputs(existing: Path, config: Source, destination: Path) -> bool:
    if not (real_directory(existing.parent) and real_directory(existing)):
        return False
    try:
        matches = inventory(existing) == config.files
    except MaintenanceError:
        return False
    if not matches:
        return False
    for name in config.files:
        target = destination / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(existing / name, target)
    return True


def _pinned_html(root: Path, existing: Path, config: Source) -> bytes:
    expected = config.files.get("source.html")
    require(expected is not None, "Pinned timeless snapshot has no source.html hash")
    cache = root / ".cache/web"
    candidates: list[Path] = []
    if real_directory(root / ".cache") and real_directory(cache):
        candidates.append(cache / f"{expected}.html")
    if real_directory(existing.parent) and real_directory(existing):
        candidates.append(existing / "source.html")
    for path in candidates:
        try:
            if stat.S_ISREG(path.lstat().st_mode):
                raw = path.read_bytes()
                if digest(raw) == expected:
                    return raw
        except FileNotFoundError:
            continue
    message = (
        "Pinned timeless HTML unavailable locally; "
        "restore it from Git or run a normal refresh"
    )
    raise MaintenanceError(message)


def snapshot(
    root: Path, source_id: str, config: Source, destination: Path, *, locked: bool
) -> Source:
    """Restore pinned local bytes or fetch the article and record generated files."""
    existing = root / "references" / source_id
    if locked and _preserve_outputs(existing, config, destination):
        return replace(config)
    raw = _pinned_html(root, existing, config) if locked else download(config.url)
    markdown = timeless_markdown(raw, config.url)
    if not locked:
        cache = root / ".cache/web"
        ensure_directory(root / ".cache")
        ensure_directory(cache)
        atomic_write(cache / f"{digest(raw)}.html", raw)
    (destination / "source.html").write_bytes(raw)
    (destination / "timeless-documentation.md").write_bytes(markdown)
    (destination / "ATTRIBUTION.md").write_text(
        ATTRIBUTION, encoding="utf-8", newline="\n"
    )
    return replace(config, transformations=TRANSFORMATIONS)
